/**
 * 作答期間（QUESTION_OPEN）僅傳送題目與選項，徹底移除答案與解析
 */
function sanitizeQuestionForOpenPhase(q, index, total) {
  return {
    index,
    total,
    number: q.number,
    title: q.title,
    scenario: q.scenario,
    options: {
      A: q.options.A,
      B: q.options.B,
      C: q.options.C,
      D: q.options.D
    }
  };
}

/**
 * 揭曉期間（QUESTION_REVEAL / FINISHED）才包含標準答案與解析
 */
function sanitizeQuestionForRevealPhase(q, index, total) {
  return {
    ...sanitizeQuestionForOpenPhase(q, index, total),
    answer: q.answer,
    explanation: q.explanation
  };
}

